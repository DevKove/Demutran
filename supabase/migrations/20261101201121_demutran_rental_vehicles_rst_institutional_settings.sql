-- DEMUTRAN: Veículos de Aluguel, RST e definições institucionais
create table if not exists public.rental_vehicles (
  id uuid primary key default gen_random_uuid(),
  placa text not null,
  marca text not null default '',
  modelo text not null default '',
  locadora text not null,
  contrato text not null default '',
  data_inicio date,
  data_fim date,
  valor_mensal numeric(12,2) not null default 0 check (valor_mensal >= 0),
  franquia_km integer check (franquia_km is null or franquia_km >= 0),
  status text not null default 'Ativo' check (status in ('Ativo','Em renovação','Suspenso','Encerrado')),
  observacoes text,
  created_by uuid not null default auth.uid() references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.traffic_accident_reports (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  data_ocorrencia timestamptz not null,
  local text not null,
  tipo text not null default 'Colisão',
  gravidade text not null default 'Sem vítima' check (gravidade in ('Sem vítima','Com vítima','Grave','Fatal')),
  envolvidos text not null default '',
  veiculos text not null default '',
  placas text not null default '',
  danos text not null default '',
  boletim_ocorrencia text not null default '',
  descricao text not null,
  providencias text not null default '',
  status text not null default 'Registrado' check (status in ('Registrado','Em apuração','Concluído','Arquivado')),
  created_by uuid not null default auth.uid() references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.institutional_settings (
  id text primary key default 'principal' check (id = 'principal'),
  orgao text not null default 'Prefeitura Municipal',
  departamento text not null default 'Departamento Municipal de Trânsito',
  endereco text not null default '',
  bairro text not null default '',
  municipio text not null default '',
  uf text not null default 'SP',
  cep text not null default '',
  telefone text not null default '',
  celular text not null default '',
  email text not null default '',
  site text not null default '',
  responsavel text not null default '',
  cargo_responsavel text not null default '',
  documento_identificador text not null default '',
  logo_url text not null default '',
  cabecalho_documento text not null default '',
  rodape_documento text not null default '',
  updated_by uuid references public.profiles(id),
  updated_at timestamptz not null default now()
);

alter table public.rental_vehicles enable row level security;
alter table public.traffic_accident_reports enable row level security;
alter table public.institutional_settings enable row level security;

grant select,insert,update,delete on public.rental_vehicles,public.traffic_accident_reports to authenticated;
grant select,insert,update on public.institutional_settings to authenticated;

drop policy if exists rental_vehicles_read on public.rental_vehicles;
create policy rental_vehicles_read on public.rental_vehicles for select to authenticated using ((select private.has_permission('veiculos_aluguel','read')));
drop policy if exists rental_vehicles_insert on public.rental_vehicles;
create policy rental_vehicles_insert on public.rental_vehicles for insert to authenticated with check ((select private.has_permission('veiculos_aluguel','create')) and created_by=(select auth.uid()));
drop policy if exists rental_vehicles_update on public.rental_vehicles;
create policy rental_vehicles_update on public.rental_vehicles for update to authenticated using ((select private.has_permission('veiculos_aluguel','update'))) with check ((select private.has_permission('veiculos_aluguel','update')));
drop policy if exists rental_vehicles_delete on public.rental_vehicles;
create policy rental_vehicles_delete on public.rental_vehicles for delete to authenticated using ((select private.has_permission('veiculos_aluguel','delete')));

drop policy if exists rst_read on public.traffic_accident_reports;
create policy rst_read on public.traffic_accident_reports for select to authenticated using ((select private.has_permission('rst','read')));
drop policy if exists rst_insert on public.traffic_accident_reports;
create policy rst_insert on public.traffic_accident_reports for insert to authenticated with check ((select private.has_permission('rst','create')) and created_by=(select auth.uid()));
drop policy if exists rst_update on public.traffic_accident_reports;
create policy rst_update on public.traffic_accident_reports for update to authenticated using ((select private.has_permission('rst','update'))) with check ((select private.has_permission('rst','update')));
drop policy if exists rst_delete on public.traffic_accident_reports;
create policy rst_delete on public.traffic_accident_reports for delete to authenticated using ((select private.has_permission('rst','delete')));

drop policy if exists institutional_settings_read on public.institutional_settings;
create policy institutional_settings_read on public.institutional_settings for select to authenticated using ((select private.has_permission('configuracoes','read')));
drop policy if exists institutional_settings_admin_insert on public.institutional_settings;
create policy institutional_settings_admin_insert on public.institutional_settings for insert to authenticated with check (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='admin' and p.status='active') and updated_by=(select auth.uid()));
drop policy if exists institutional_settings_admin_update on public.institutional_settings;
create policy institutional_settings_admin_update on public.institutional_settings for update to authenticated using (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='admin' and p.status='active')) with check (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='admin' and p.status='active') and updated_by=(select auth.uid()));

insert into public.role_permissions(role,module,action)
select r.role,m.module,a.action
from (values ('admin'),('gestor'),('agente'),('consulta')) as r(role)
cross join (values ('veiculos_aluguel'),('rst')) as m(module)
cross join (values ('read'),('create'),('update'),('delete')) as a(action)
where r.role in ('admin','gestor')
   or (r.role='agente' and a.action in ('read','create','update'))
   or (r.role='consulta' and a.action='read')
on conflict(role,module,action) do nothing;

insert into public.institutional_settings(id) values ('principal') on conflict(id) do nothing;

create index if not exists rental_vehicles_created_by_idx on public.rental_vehicles(created_by);
create index if not exists rental_vehicles_placa_idx on public.rental_vehicles(placa);
